# Deliberately use a DIFFERENT model to judge than to generate,
# to reduce self-preference bias in scoring.
GENERATOR_PROVIDER_HINT = "groq"   # whichever your generate() picks by default


def judge(prompt_text: str) -> str:
    """Calls the judge LLM. Reuses your existing fallback chain — Gemini will
    likely answer here since it's tier 2, giving natural separation from Groq."""
    result, provider_used = generate([{"role": "user", "content": prompt_text}])
    return result, provider_used


def score_context_precision(retrieved_ids: list[str], ground_truth_ids: list[str]) -> float:
    if not retrieved_ids:
        return 0.0
    relevant = [cid for cid in retrieved_ids if cid in ground_truth_ids]
    return len(relevant) / len(retrieved_ids)


def score_context_recall(retrieved_ids: list[str], ground_truth_ids: list[str]) -> float:
    if not ground_truth_ids:
        return 1.0
    found = [cid for cid in ground_truth_ids if cid in retrieved_ids]
    return len(found) / len(ground_truth_ids)


import re

def score_faithfulness(answer: str, context_chunks: list[str]) -> tuple[float, str]:
    context_text = "\n\n".join(context_chunks)
    prompt = (
        "You are a strict evaluation judge. Given source documents and a generated answer, "
        "determine what fraction of claims in the answer are directly supported by the sources. "
        "Respond ONLY in this exact format: SCORE: X.X | REASON: one sentence\n"
        "Where X.X is a number from 0.0 to 1.0.\n\n"
        f"Sources:\n{context_text}\n\nGenerated Answer:\n{answer}"
    )
    result, provider = judge(prompt)
    score = None
    try:
        m = re.search(r"SCORE:\s*([0-9\.]+)", result, re.IGNORECASE)
        if m:
            score = float(m.group(1))
    except Exception:
        score = None
    return score, result


def score_answer_relevancy(question: str, answer: str) -> tuple[float, str]:
    prompt = (
        "You are a strict evaluation judge. Does the following answer actually address "
        "the question asked, regardless of factual correctness? "
        "Respond ONLY in this exact format: SCORE: X.X | REASON: one sentence\n"
        "Where X.X is a number from 0.0 (off-topic) to 1.0 (directly on-topic).\n\n"
        f"Question: {question}\n\nAnswer: {answer}"
    )
    result, provider = judge(prompt)
    score = None
    try:
        m = re.search(r"SCORE:\s*([0-9\.]+)", result, re.IGNORECASE)
        if m:
            score = float(m.group(1))
    except Exception:
        score = None
    return score, result


def run_eval():
    results = []

    for case in GOLDEN_DATASET:
        print(f"\n{'='*60}")
        print(f"Question: {case['question']}")

        chunks = retrieve(
            case["question"],
            where={"proposal_id": case["proposal_id"]}
        )
        retrieved_ids = [c["id"] for c in chunks]
        context_texts = [c["document"] for c in chunks]

        if not chunks:
            print("  No chunks retrieved — skipping generation.")
            continue

        messages = build_prompt(case["question"], chunks)
        answer, gen_provider = generate(messages)

        precision = score_context_precision(retrieved_ids, case["ground_truth_context_ids"])
        recall = score_context_recall(retrieved_ids, case["ground_truth_context_ids"])
        faithfulness, faith_reason = score_faithfulness(answer, context_texts)
        relevancy, rel_reason = score_answer_relevancy(case["question"], answer)

        print(f"  Generated by: {gen_provider}")
        print(f"  Context Precision: {precision:.2f}")
        print(f"  Context Recall:    {recall:.2f}")
        print(f"  Faithfulness:      {faithfulness} ({faith_reason})")
        print(f"  Answer Relevancy:  {relevancy} ({rel_reason})")

        results.append({
            "question": case["question"],
            "precision": precision,
            "recall": recall,
            "faithfulness": faithfulness,
            "relevancy": relevancy,
        })

    print(f"\n{'='*60}")
    print("SUMMARY")
    if results:
        avg_precision = sum(r["precision"] for r in results) / len(results)
        avg_recall = sum(r["recall"] for r in results) / len(results)
        valid_faith = [r["faithfulness"] for r in results if r["faithfulness"] is not None]
        avg_faith = sum(valid_faith) / len(valid_faith) if valid_faith else 0.0
        valid_rel = [r["relevancy"] for r in results if r["relevancy"] is not None]
        avg_rel = sum(valid_rel) / len(valid_rel) if valid_rel else 0.0

        print(f"Avg Context Precision: {avg_precision:.2f}")
        print(f"Avg Context Recall:    {avg_recall:.2f}")
        print(f"Avg Faithfulness:       {avg_faith:.2f}")
        print(f"Avg Answer Relevancy:   {avg_rel:.2f}")

    return results


if __name__ == "__main__":
    run_eval()